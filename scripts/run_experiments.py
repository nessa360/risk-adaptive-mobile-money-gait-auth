"""Run experiments from a prepared NPZ file.

Expected NPZ keys: train_windows, train_labels, test_windows, and test_labels. The split must be created upstream by session or enrollment protocol. An optional metadata JSON path can describe available condition fields. No data is generated by this script.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import numpy as np
from gait_auth.preprocessing import Normalizer
from gait_auth.models import ClassicalModel
from gait_auth.experiments import (
    run_e1,
    run_e1_verification,
    _split_enrollment_verification,
    status_e2,
    status_e3,
    status_e4,
    status_e6,
    save_json,
    benchmark_inference,
)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--npz", required=True)
    parser.add_argument("--output", default="results")
    parser.add_argument("--metadata", default=None)
    args = parser.parse_args()
    out = Path(args.output); (out / "tables").mkdir(parents=True, exist_ok=True); (out / "json").mkdir(parents=True, exist_ok=True)
    data = np.load(args.npz)
    train_windows, train_labels = data["train_windows"], data["train_labels"]
    test_windows, test_labels = data["test_windows"], data["test_labels"]
    normalizer = Normalizer().fit(train_windows)
    train_windows = normalizer.transform(train_windows)
    test_windows = normalizer.transform(test_windows)
    from gait_auth.features import extract_features
    x_train = extract_features(train_windows)
    x_test = extract_features(test_windows)
    models = {name: ClassicalModel(name).fit(x_train, train_labels) for name in ("svm", "random_forest", "knn")}
    y_test = test_labels
    e1 = run_e1(models, x_test, y_test, out / "tables")
    enrollment_x, enrollment_y, verification_x, verification_y = _split_enrollment_verification(x_test, y_test)
    run_e1_verification(
        x_train,
        train_labels,
        enrollment_x,
        enrollment_y,
        verification_x,
        verification_y,
        out / "tables",
    )
    for name, model in models.items():
        benchmark_inference(model, x_test, out / "json", name)
    metadata = set()
    if args.metadata:
        metadata = set(json.loads(Path(args.metadata).read_text()).get("columns", []))
    statuses = [
        status_e2(metadata).to_dict(),
        status_e3(metadata).to_dict(),
        status_e4(bool("mimicry_label" in metadata)).to_dict(),
        status_e6(bool("survey_response" in metadata)).to_dict(),
    ]
    save_json(statuses, out / "json" / "experiment_status.json")
    print(e1.to_string(index=False))


if __name__ == "__main__":
    main()
